#!/usr/bin/env node
/**
 * Builds components/icons/: only the lucide icons the app actually uses, as
 * plain SVG components with no icon runtime.
 *
 * Why: lucide-react's shared runtime cost ~10KB gzipped on the sales screen,
 * which was the difference between meeting and missing the 200KB budget.
 * Each icon is its own module behind a side-effect-free barrel, so a route
 * ships only the icons it imports rather than every icon any route uses.
 * The icon artwork is lucide's (ISC licence); only the wrapper is ours.
 *
 * Run after adding an icon: `npm run icons`.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const iconsDir = join(root, 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const outDir = join(root, 'components', 'icons');

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (full.startsWith(outDir)) continue;
    if (statSync(full).isDirectory()) walk(full, files);
    else if (/\.tsx?$/.test(entry)) files.push(full);
  }
  return files;
}

const used = new Set();
for (const file of ['app', 'components'].flatMap((d) => walk(join(root, d)))) {
  const code = readFileSync(file, 'utf8');
  for (const match of code.matchAll(/import\s*\{([^}]+)\}\s*from\s*['"](?:lucide-react|@\/components\/icons)['"]/g)) {
    for (const name of match[1].split(',').map((s) => s.trim()).filter(Boolean)) {
      if (!name.startsWith('type ')) used.add(name);
    }
  }
}

const kebab = (name) =>
  name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/([a-zA-Z])(\d)/g, '$1-$2')
    .toLowerCase();

const icons = [];
for (const name of [...used].sort()) {
  const file = join(iconsDir, `${kebab(name)}.mjs`);
  let source;
  try {
    source = readFileSync(file, 'utf8');
  } catch {
    console.error(`icons — no lucide icon for ${name} (looked for ${relative(root, file)})`);
    process.exit(1);
  }
  // Renamed icons are re-exports of their new file; follow the alias.
  for (let hops = 0; hops < 3; hops++) {
    const alias = /export \{ default \} from '\.\/([\w-]+\.mjs)'/.exec(source);
    if (!alias) break;
    source = readFileSync(join(iconsDir, alias[1]), 'utf8');
  }
  const match = /const __iconData = (\{[\s\S]*?\n\});/.exec(source);
  if (!match) {
    console.error(`icons — could not read ${name}`);
    process.exit(1);
  }
  // The icon data is a plain literal (arrays, strings, objects); evaluate it.
  const node = Function(`return ${match[1]}`)().node;
  const children = node.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    return [tag, rest];
  });
  icons.push({ name, children });
}

const header = '/* Generated by scripts/make-icon-set.mjs -- do not edit by hand. */\n';

const makeSource = `${header}/* Icon artwork from Lucide (https://lucide.dev), ISC licence. */
import { createElement, type SVGProps } from 'react';

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'ref'> {
  size?: number;
  strokeWidth?: number;
}

type Node = readonly (readonly [string, Record<string, string | number>])[];

export function make(node: Node) {
  return function Icon({ size = 24, strokeWidth = 2, ...props }: IconProps) {
    return createElement(
      'svg',
      {
        xmlns: 'http://www.w3.org/2000/svg',
        width: size,
        height: size,
        viewBox: '0 0 24 24',
        fill: 'none',
        stroke: 'currentColor',
        strokeWidth,
        strokeLinecap: 'round',
        strokeLinejoin: 'round',
        'aria-hidden': props['aria-label'] ? undefined : true,
        ...props,
      },
      node.map(([tag, attrs], i) => createElement(tag, { key: i, ...attrs }))
    );
  };
}
`;

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'make.ts'), makeSource);

for (const { name, children } of icons) {
  const body = `import { make } from './make';\n\nexport const ${name} = /*#__PURE__*/ make(${JSON.stringify(children)});\n`;
  writeFileSync(join(outDir, `${name}.ts`), header + body);
}

const barrel = [
  "export type { IconProps } from './make';",
  ...icons.map(({ name }) => `export { ${name} } from './${name}';`),
].join('\n');
writeFileSync(join(outDir, 'index.ts'), `${header}${barrel}\n`);

// Scoped to this folder: lets the bundler drop icons a route never imports.
writeFileSync(join(outDir, 'package.json'), `${JSON.stringify({ sideEffects: false }, null, 2)}\n`);

console.log(`icons — wrote ${icons.length} icons to ${relative(root, outDir)}/`);
